//! Reads validity dates from certificate files: PEM (incl. chains), DER and PKCS#12.

use crate::model::CertInfo;
use anyhow::{anyhow, Result};
use chrono::{DateTime, Utc};
use x509_parser::pem::Pem;
use x509_parser::prelude::{FromDer, X509Certificate};

/// Error message the UI recognises to ask for a PFX password.
pub const PASSWORD_REQUIRED: &str = "This file is password protected";

fn iso(ts: i64) -> String {
    DateTime::<Utc>::from_timestamp(ts, 0).map(|d| d.to_rfc3339()).unwrap_or_default()
}

fn info(cert: &X509Certificate) -> CertInfo {
    CertInfo {
        not_after: iso(cert.validity().not_after.timestamp()),
        not_before: iso(cert.validity().not_before.timestamp()),
        subject: cert.subject().to_string(),
        issuer: cert.issuer().to_string(),
    }
}

/// The certificate that expires first wins: in a chain, any expiry breaks the whole thing.
fn earliest(ders: &[Vec<u8>]) -> Option<CertInfo> {
    ders.iter()
        .filter_map(|der| X509Certificate::from_der(der).ok().map(|(_, c)| (c.validity().not_after.timestamp(), info(&c))))
        .min_by_key(|(ts, _)| *ts)
        .map(|(_, info)| info)
}

pub fn parse(bytes: &[u8], password: Option<&str>) -> Result<CertInfo> {
    if bytes.windows(10).any(|w| w == b"-----BEGIN") {
        let ders: Vec<Vec<u8>> = Pem::iter_from_buffer(bytes)
            .filter_map(|p| p.ok())
            .filter(|p| p.label == "CERTIFICATE" || p.label == "TRUSTED CERTIFICATE")
            .map(|p| p.contents)
            .collect();
        return earliest(&ders).ok_or_else(|| anyhow!("No certificate found in this PEM file (it may hold only a key)"));
    }
    if let Ok((_, cert)) = X509Certificate::from_der(bytes) {
        return Ok(info(&cert));
    }
    parse_pkcs12(bytes, password.unwrap_or(""))
}

fn parse_pkcs12(bytes: &[u8], password: &str) -> Result<CertInfo> {
    let store = p12_keystore::KeyStore::from_pkcs12(bytes, password).map_err(|e| {
        let msg = e.to_string().to_lowercase();
        if msg.contains("mac") || msg.contains("password") || msg.contains("decrypt") {
            anyhow!(PASSWORD_REQUIRED)
        } else {
            anyhow!("Unrecognised file format")
        }
    })?;
    let ders: Vec<Vec<u8>> = store
        .entries()
        .flat_map(|(_, entry)| match entry {
            p12_keystore::KeyStoreEntry::PrivateKeyChain(chain) => {
                chain.chain().iter().map(|c| c.as_der().to_vec()).collect::<Vec<_>>()
            }
            p12_keystore::KeyStoreEntry::Certificate(c) => vec![c.as_der().to_vec()],
            _ => vec![],
        })
        .collect();
    earliest(&ders).ok_or_else(|| anyhow!("No certificate inside this PKCS#12 file"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn fixture(name: &str) -> Vec<u8> {
        std::fs::read(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures").join(name)).unwrap()
    }

    // fixtures are generated by tests/fixtures/make.sh with a not-after of 2030-01-01
    #[test]
    fn pem() {
        let i = parse(&fixture("cert.pem"), None).unwrap();
        assert!(i.not_after.starts_with("2030-01-01"), "{}", i.not_after);
        assert!(i.subject.contains("certy.test"));
    }

    #[test]
    fn der() {
        assert!(parse(&fixture("cert.der"), None).unwrap().not_after.starts_with("2030-01-01"));
    }

    #[test]
    fn pfx_needs_password() {
        let err = parse(&fixture("cert.pfx"), None).unwrap_err().to_string();
        assert_eq!(err, PASSWORD_REQUIRED);
        assert!(parse(&fixture("cert.pfx"), Some("hunter2")).unwrap().not_after.starts_with("2030-01-01"));
    }

    #[test]
    fn garbage_is_rejected() {
        assert!(parse(b"not a certificate at all", None).is_err());
    }
}
